// Runs `fn(client)` inside one transaction on a single pooled connection.
// Commits when fn resolves, rolls back when it throws (the error is re-thrown).
export async function withTransaction(pool, fn) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await fn(client);
    await client.query('COMMIT');
    return result;
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    throw err;
  } finally {
    client.release();
  }
}
